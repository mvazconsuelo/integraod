  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT NOT NULL,
  price_cents INTEGER NOT NULL DEFAULT 0 CHECK (price_cents >= 0),
  position INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_treatments_category ON treatments(category, position);

